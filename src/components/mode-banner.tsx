"use client";

import { AlertTriangle, FlaskConical, ServerOff } from "lucide-react";
import Link from "next/link";
import { useActiveModel } from "@/lib/hooks";
import { USING_PROXY, API_BASE_URL } from "@/lib/config";

/**
 * Global status strip. Three states:
 *  - backend unreachable  -> explains how to start it
 *  - mock mode            -> "Demo Mode — Trained model not loaded"
 *  - trained mode error   -> model failed to load
 * Renders nothing when a trained model is serving normally.
 */
export function ModeBanner() {
  const { data, isError, isLoading } = useActiveModel();

  if (isLoading) return null;

  if (isError || !data) {
    return (
      <div role="status" className="border-b border-warn/25 bg-warn-soft">
        <div className="mx-auto flex max-w-6xl items-start gap-3 px-4 py-2.5 text-sm text-warn sm:px-6 lg:px-8">
          <ServerOff className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />
          <p>
            <span className="font-semibold">Backend unreachable.</span> The API at <code className="font-mono text-xs">{API_BASE_URL}</code>
            {USING_PROXY ? " (proxied to BACKEND_INTERNAL_URL)" : ""} did not respond. Start it with <code className="font-mono text-xs">make backend</code>.
          </p>
        </div>
      </div>
    );
  }

  if (data.status === "error") {
    return (
      <div role="status" className="border-b border-danger/25 bg-danger-soft">
        <div className="mx-auto flex max-w-6xl items-start gap-3 px-4 py-2.5 text-sm text-danger sm:px-6 lg:px-8">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />
          <p>
            <span className="font-semibold">Model failed to load.</span> {data.error ?? data.message}{" "}
            <Link href="/model" className="underline underline-offset-2">
              Details
            </Link>
          </p>
        </div>
      </div>
    );
  }

  if (data.is_mock) {
    return (
      <div role="status" data-testid="mode-banner" className="border-b border-warn/25 bg-warn-soft">
        <div className="mx-auto flex max-w-6xl items-start gap-3 px-4 py-2.5 text-sm text-warn sm:px-6 lg:px-8">
          <FlaskConical className="mt-0.5 h-4 w-4 shrink-0" aria-hidden />
          <p>
            <span className="font-semibold">Demo Mode — Trained model not loaded.</span> Predictions are deterministic placeholders generated by the mock
            predictor. Follow <Link href="/docs#training" className="underline underline-offset-2">docs/TRAINING.md</Link> to train and activate a real model.
          </p>
        </div>
      </div>
    );
  }

  return null;
}
